def _copy_federation(state: dict[str, Any]) -> dict[str, Any]:
    return {{
        "federation_id": state["federation_id"],
        "federation_epoch": state["federation_epoch"],
        "members": dict(state["members"]),
        "routes": dict(state["routes"]),
        "exports": frozenset(state["exports"]),
    }}


def federation_genesis(state: dict[str, Any], federation_id: str, epoch: str) -> dict[str, Any]:
    if state["federation_id"] is not None or state["federation_epoch"] is not None:
        raise ValueError("federation already exists")
    if state["members"] or state["routes"] or state["exports"]:
        raise ValueError("federation genesis requires empty state")
    result = _copy_federation(state)
    result["federation_id"] = federation_id
    result["federation_epoch"] = epoch
    return result


def member_join(state: dict[str, Any], context: str) -> dict[str, Any]:
    if state["federation_id"] is None:
        raise ValueError("federation missing")
    if state["members"].get(context, "ABSENT") != "ABSENT":
        raise ValueError("member is not absent")
