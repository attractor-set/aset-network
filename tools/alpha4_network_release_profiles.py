def _exact_observation(value: dict[str, Any]) -> bool:
    fields = {{"import_id", "source_context", "target_context", "evidence_digest"}}
    if set(value) != fields:
        return False
    if not all(isinstance(value[key], str) and value[key] for key in fields):
        return False
    digest = value["evidence_digest"]
    return (
        isinstance(digest, str)
        and len(digest) == 71
        and digest.startswith("sha256:")
        and all(ch in "0123456789abcdef" for ch in digest[7:])
    )


def _network_result(accepted: bool, code: str, changed: bool) -> dict[str, Any]:
    return {{
        "accepted": accepted,
        "code": code,
        "state_changed": changed,
        "seed_projection": {{
            "component": "ASET-COMPONENT-OBSERVE-UNKNOWN" if accepted else None,
            "recognition": "UNKNOWN" if accepted else "NOT_APPLICABLE",
            "effect_permitted": False,
        }},
    }}


def admit_import(
    imports: list[dict[str, Any]],
    observation: dict[str, Any],
    seed_state: dict[str, Any],
) -> tuple[list[dict[str, Any]], dict[str, Any], dict[str, Any]]:
    current_imports = [dict(item) for item in imports]
    current_seed = dict(seed_state)
    if not _exact_observation(observation):
        raise ValueError("exact import observation required")
    same_id = [item for item in current_imports if item["import_id"] == observation["import_id"]]
    if observation in same_id:
        next_imports = current_imports
        result = _network_result(True, "IDEMPOTENT_REPLAY", False)
    elif same_id:
        return current_imports, current_seed, _network_result(False, "IDENTIFIER_CONFLICT", False)
    else:
        next_imports = [*current_imports, dict(observation)]
        result = _network_result(True, "IMPORT_ADMITTED", True)
    next_seed = _seed["apply_component"](
        current_seed,
        "ASET-COMPONENT-OBSERVE-UNKNOWN",
        evidence=observation["evidence_digest"],
    )
    return next_imports, next_seed, result


