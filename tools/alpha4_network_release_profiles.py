def build_release_profiles(seed_profiles_root: Path, output: Path) -> dict[str, Any]:
    binding = parse_seed_binding()
    seed_evidence = check_seed_companion_bases(seed_profiles_root)
    if output.exists():
        shutil.rmtree(output)
    (output / "base/seed/en").mkdir(parents=True)
    (output / "base/seed/python").mkdir(parents=True)
    (output / "en").mkdir(parents=True)
    (output / "python").mkdir(parents=True)

    seed_english_rel, seed_english_sha = binding.companions["ENGLISH"]
    seed_python_rel, seed_python_sha = binding.companions["PYTHON"]
    seed_english_target = output / "base/seed/en/Seed.md"
    seed_python_target = output / "base/seed/python/aset_seed_alpha4.py"
    shutil.copy2(seed_profiles_root / seed_english_rel, seed_english_target)
    shutil.copy2(seed_profiles_root / seed_python_rel, seed_python_target)
    require(sha256(seed_english_target) == seed_english_sha, "copied Seed English base drift")
    require(sha256(seed_python_target) == seed_python_sha, "copied Seed Python base drift")

    records = _manifest_records(ROOT)
    english = output / "en/Network.md"
    python = output / "python/aset_network_alpha4.py"
    write_english(english, seed_english_sha, records)
    write_python(python, seed_python_sha, records)

    parsed = parse_english(english)
    expected = [
        {
            key: item[key]
            for key in (
                "subject",
                "component_id",
                "transition_binding",
                "operational",
                "relational",
                "causal",
                "seed_extension",
            )
        }
        for item in records
    ]
    require(parsed == expected, "Network controlled English round-trip mismatch")

    return {
        "document_type": "aset-network-release-companion-evidence",
        "semantic_precedence": "NONE",
        "relation": "EXTENSION_OF_EXACT_SEED_COMPANIONS",
        "seed_profile_tree_digest": seed_evidence["profile_tree_digest"],
        "base_expressions": {
            "english": {"path": "base/seed/en/Seed.md", "sha256": seed_english_sha},
            "python": {"path": "base/seed/python/aset_seed_alpha4.py", "sha256": seed_python_sha},
        },
        "network_expressions": {
            "english": {"path": "en/Network.md", "sha256": sha256(english)},
            "python": {"path": "python/aset_network_alpha4.py", "sha256": sha256(python)},
        },
        "english_components_checked": len(records),
        "status": "PASS",
    }


