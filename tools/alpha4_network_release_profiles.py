def _sha256(path: Path) -> str:
    return "sha256:" + hashlib.sha256(path.read_bytes()).hexdigest()


def _load_seed_base() -> dict[str, Any]:
    if _sha256(BASE_SEED_EXPRESSION_PATH) != BASE_SEED_EXPRESSION_SHA256:
        raise RuntimeError("exact Seed Python companion byte identity mismatch")
