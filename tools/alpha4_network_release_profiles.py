class ReleaseProfileError(RuntimeError):
    pass


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ReleaseProfileError(message)


def _manifest_records(root: Path = ROOT) -> list[dict[str, str]]:
    records: list[dict[str, str]] = []
    for subject, relative in SUBJECT_MANIFESTS:
        lines = [
            line.strip()
            for line in (root / relative).read_text(encoding="utf-8").splitlines()
            if line.strip()
        ]
        causal = {}
        for line in lines:
            if line.startswith("CAUSAL-BIND "):
                _, component_id, causal_transition = line.split()
                causal[component_id] = causal_transition
        for line in lines:
            if not line.startswith("PAIR "):
                continue
            parts = line.split()
            require(len(parts) == 6, f"bad PAIR declaration in {relative}: {line}")
            _, component_id, transition_binding, relational, _reflection, pairing = parts
            require(component_id in causal, f"causal binding missing for {component_id}")
            operational = transition_binding
            if subject == "NETWORK":
                operational = {
                    "ASET-NETWORK-COMPONENT-ADMIT-FRESH": "ADMIT-FRESH",
                    "ASET-NETWORK-COMPONENT-ADMIT-REPLAY": "ADMIT-REPLAY",
                    "ASET-NETWORK-COMPONENT-REJECT-CONFLICT": "REJECT-CONFLICT",
                }[component_id]
            seed_extension = "NONE"
            if subject == "NETWORK" and component_id in {
                "ASET-NETWORK-COMPONENT-ADMIT-FRESH",
                "ASET-NETWORK-COMPONENT-ADMIT-REPLAY",
            }:
                seed_extension = "OBSERVE-UNKNOWN"
            records.append(
                {
                    "subject": subject,
                    "component_id": component_id,
                    "transition_binding": transition_binding,
                    "operational": operational,
                    "relational": relational,
                    "causal": causal[component_id],
                    "pairing": pairing,
                    "seed_extension": seed_extension,
                }
            )
    return records


def write_english(target: Path, seed_english_sha256: str, records: list[dict[str, str]]) -> None:
    lines = [
        "# ASET Network 0.1.0-alpha.4 — generated release companion extension",
        "",
        "Generated by release CI. Semantic precedence: none.",
        f"Exact Seed English base SHA-256: `{seed_english_sha256}`",
        "",
        (
            "This document adds only Network-owned expression content; "
            "the Seed companion remains the exact base expression."
        ),
        "",
    ]
    for item in records:
        lines += [
            f"### {item['component_id']}",
            f"Subject: `{item['subject']}`",
            f"Transition: `{item['transition_binding']}`",
            f"Operational: `{item['operational']}`",
            f"Relational: `{item['relational']}`",
            f"Causal: `{item['causal']}`",
            f"Seed extension: `{item['seed_extension']}`",
            "",
        ]
    target.write_text("\n".join(lines), encoding="utf-8")


def parse_english(path: Path) -> list[dict[str, str]]:
    text = path.read_text(encoding="utf-8")
    sections = re.split(r"(?m)^### ", text)[1:]
    records: list[dict[str, str]] = []
    for section in sections:
        lines = [line.strip() for line in section.splitlines() if line.strip()]
        component_id = lines[0]
        fields: dict[str, str] = {}
        for line in lines[1:]:
            match = re.fullmatch(r"([A-Za-z ]+): `(.*)`", line)
            if match:
                fields[match.group(1)] = match.group(2)
        records.append(
            {
                "subject": fields["Subject"],
                "component_id": component_id,
                "transition_binding": fields["Transition"],
                "operational": fields["Operational"],
                "relational": fields["Relational"],
                "causal": fields["Causal"],
                "seed_extension": fields["Seed extension"],
            }
        )
    return records


